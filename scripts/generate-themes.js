function scaleVars(name, scale) {
  return STEPS.map((s) => `  --${name}-${s}: ${rgbVar(scale[s])};`).join("\n")
}

let css = "/* GENERATED by scripts/generate-themes.js — do not edit by hand. */\n"
for (const [id, t] of Object.entries(THEMES)) {
  const dark = t.scheme === "dark"
  const blocks = [
    scaleVars("richblack", neutral(t.neutral)),
    scaleVars("yellow", tonal(t.accent, 50, dark)),
    scaleVars("richblue", tonal(t.secondary, 300, dark)),
    scaleVars("blue", tonal(t.info, 100, dark)),
    scaleVars("caribbeangreen", tonal(t.success, 100, dark)),
    scaleVars("brown", tonal(t.warning, 100, dark)),
    scaleVars("pink", tonal(t.danger, 200, dark)),
    // Light-surface grey scale kept for the few places that referenced it.
    scaleVars("pure-greys", neutral(t.neutral)),
    `  --font-display: ${t.fontDisplay};`,
    `  --radius-card: ${t.radius};`,
    `  --shadow-card: ${t.shadow};`,
    `  color-scheme: ${t.scheme};`,
  ]
  const selector = id === "daylight" ? `:root,\n[data-theme="daylight"]` : `[data-theme="${id}"]`
  css += `\n${selector} {\n${blocks.join("\n")}\n}\n`
}

const out = path.join(__dirname, "..", "src", "styles", "themes.css")
fs.mkdirSync(path.dirname(out), { recursive: true })
fs.writeFileSync(out, css)
