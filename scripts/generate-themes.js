/*
 * Generates src/styles/themes.css — one block of CSS variables per theme.
 * Tailwind reads them in tailwind.config.js as rgb(var(--token) / <alpha-value>),
 * so every existing utility (bg-richblack-800, text-yellow-50, ...) re-colours
 * itself when <html data-theme="..."> changes.
 *
 * Run:  node scripts/generate-themes.js
 *
 * Token roles (names are historical, roles are what matter):
 *   richblack  neutral scale. 900 = page background, 800 = card, 700 = border,
 *              5 = strongest text. On light themes the scale is inverted, so the
 *              same classes work on every theme.
 *   yellow     primary accent. 50 = main, 100 = hover.
 *   richblue   secondary accent (focus rings, gradients).
 *   blue / caribbeangreen / brown / pink   info / success / warning / danger.
 */
const fs = require("fs")
const path = require("path")

const STEPS = [5, 25, 50, 100, 200, 300, 400, 500, 600, 700, 800, 900]

const hexToRgb = (h) => {
  const n = parseInt(h.replace("#", ""), 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}
const mix = (a, b, t) => {
  const A = hexToRgb(a)
  const B = hexToRgb(b)
  return A.map((v, i) => Math.round(v + (B[i] - v) * t))
}
const rgbVar = (rgb) => rgb.join(" ")

// A tonal scale around one main colour. `dark` themes get shades toward black
// for the high steps; light themes get tints toward white so that tinted
// backgrounds (e.g. bg-pink-900/30) stay pale instead of turning muddy-dark.
function tonal(main, mainStep, dark) {
  const out = {}
  const idx = STEPS.indexOf(mainStep)
  STEPS.forEach((s, i) => {
    if (i === idx) out[s] = hexToRgb(main)
    else if (i < idx) out[s] = mix(main, "#ffffff", 0.9 - (i / idx) * 0.8 * 0.9)
    else {
      const t = (i - idx) / (STEPS.length - 1 - idx)
      out[s] = dark ? mix(main, "#000000", 0.12 + t * 0.83) : mix(main, "#ffffff", 0.35 + t * 0.6)
    }
  })
  // Hover step (the one right after the main) should be a slightly darker shade
  // on both kinds of theme, never a lighter tint.
  if (idx + 1 < STEPS.length) out[STEPS[idx + 1]] = mix(main, "#000000", 0.14)
  return out
}

const neutral = (list) => Object.fromEntries(STEPS.map((s, i) => [s, hexToRgb(list[i])]))

